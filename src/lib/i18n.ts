/** Fill {placeholders} in a translated string: format(t.reportSub, { n: 5 }). */
export function format(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => key in values ? String(values[key]) : match);
}

/** Saved choice first, then the browser's language, then English. */
export function detectLang(cookieValue: string | undefined, acceptLanguage: string | null | undefined): Lang {
  if (cookieValue === "en" || cookieValue === "hi") return cookieValue;
  const preferred = (acceptLanguage ?? "").split(",").map((part) => part.trim().slice(0, 2).toLowerCase());
  return preferred.find((code) => code === "hi" || code === "en") === "hi" ? "hi" : "en";
}
