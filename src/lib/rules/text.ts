/**
 * Text handling for the rule-based call analyzer: one canonical spelling for Hindi / Hinglish / English, and a cut of the
 * call into short "units" (sentences, or ~20-word pieces when the transcript has no punctuation) that keep their position in
 * the ORIGINAL text, so every quote the analysis shows is a real piece of what was said.
 */

/** Normalised text plus, for every normalised character, where it came from in the original (map[norm.length] = raw.length). */
export type Mapped = { norm: string; map: number[] };

// Characters that carry no meaning for matching: zero-width marks and the Devanagari nukta (बढ़िया / बढिया, ज़रूरी / जरूरी).
const DROP = new Set([0x200b, 0x200c, 0x200d, 0x2060, 0xfeff, 0x093c]);
// क़ ख़ ग़ ज़ ड़ ढ़ फ़ य़ written as one code point → the plain letter.
const PRECOMPOSED: Record<number, string> = { 0x958: "क", 0x959: "ख", 0x95a: "ग", 0x95b: "ज", 0x95c: "ड", 0x95d: "ढ", 0x95e: "फ", 0x95f: "य" };

export function normalizeMapped(raw: string): Mapped {
  let norm = "";
  const map: number[] = [];
  let index = 0;
  for (const ch of raw) {
    const code = ch.codePointAt(0)!;
    let out: string;
    if (DROP.has(code)) out = "";
    else if (code === 0x901) out = "ं"; // chandrabindu → anusvara: दूँगा / दूंगा
    else if (PRECOMPOSED[code]) out = PRECOMPOSED[code];
    else if (code === 0x2019 || code === 0x2018 || code === 0x60) out = "'";
    else out = ch.toLocaleLowerCase();
    norm += out;
    for (let k = 0; k < out.length; k += 1) map.push(index);
    index += ch.length;
  }
  map.push(raw.length);
  return { norm, map };
}

/** Source text of a pattern written with natural spellings → the same normal form as the text it will be matched against. */
export function normalizePattern(source: string) {
  let out = "";
  for (const ch of source) {
    const code = ch.codePointAt(0)!;
    if (DROP.has(code)) continue;
    if (code === 0x901) out += "ं";
    else if (PRECOMPOSED[code]) out += PRECOMPOSED[code];
    else out += ch;
  }
  return out;
}

/** Compile a regular expression written with natural Devanagari spellings (it is normalised like the text). Write it in lower case. */
export const rx = (source: string, flags = "gu") => new RegExp(normalizePattern(source), flags);

/** The same expression without the "g" flag, so .test() has no hidden state between calls. */
export const once = (pattern: RegExp) => new RegExp(pattern.source, pattern.flags.replace("g", ""));

export type Unit = {
  /** Start / end in the original text, trimmed. */
  s: number; e: number;
  /** Start / end in the normalised text. */
  ns: number; ne: number;
  text: string;
  /** Normalised text of the unit. */
  n: string;
  words: number;
  /** A speaker label written in the transcript ("Interviewer:", "ग्राहक:") – normalised – if there was one. */
  label?: string;
  /** The unit follows a timestamp line, i.e. a new speaker block started before it. */
  block: number;
  /** True when the original ended the unit with a question mark. */
  asked: boolean;
};

const STAMP_LINE = /^\s*(?:\[?\d{1,2}:\d{2}(?::\d{2})?\]?)\s*$/;
const NOISE_LINE = /^\s*(?:this content was generated by ai\.?|generated by ai|transcript(?:ion)?(?: by .*)?)\s*$/i;

const LABEL_WORDS = "interviewer|interviewee|इंटरव्यूअर|इंटरव्यूवर|इंटरव्यू लेने वाला|customer|ग्राहक|कस्टमर|respondent|participant|प्रतिभागी|question|प्रश्न|सवाल|answer|उत्तर|जवाब|host|guest|team|trata team|speaker\\s*[0-9a-z]+|स्पीकर\\s*[0-9a-z]+|q|a|i|c";
const LABEL_AT_START = new RegExp(`^\\s*(?:${normalizePattern(LABEL_WORDS)})\\s*[:：]\\s*`, "u");
// A label in the middle of a line: "...है? ग्राहक: हाँ" – cut before it so it starts its own unit.
const LABEL_INLINE = new RegExp(`(?<=[.!?।…\\s])((?:interviewer|इंटरव्यूअर|customer|ग्राहक|कस्टमर|respondent|question|प्रश्न|answer|उत्तर|जवाब|speaker\\s*[0-9]+|स्पीकर\\s*[0-9]+)\\s*[:：])`, "gu");

/** Soft places to cut a long unpunctuated stretch: just before words that usually start a new thought. */
const SOFT_BREAK = new Set(normalizePattern("और लेकिन मगर पर तो फिर क्योंकि इसलिए जैसे अगर अच्छा हां हाँ नहीं मतलब बट एंड but and so because then also if actually basically well okay ok").split(" "));
const MAX_WORDS = 26;
const MIN_CHUNK = 9;

type RawPiece = { ns: number; ne: number; block: number };

/** Cuts the normalised text into pieces at sentence ends, line ends, timestamps and inline speaker labels. */
function sentencePieces(norm: string): RawPiece[] {
  const pieces: RawPiece[] = [];
  let block = 0;
  let lineStart = 0;
  const lines: Array<{ s: number; e: number }> = [];
  for (let i = 0; i <= norm.length; i += 1) {
    if (i === norm.length || norm[i] === "\n") { lines.push({ s: lineStart, e: i }); lineStart = i + 1; }
  }
  for (const line of lines) {
    const text = norm.slice(line.s, line.e);
    if (STAMP_LINE.test(text)) { block += 1; continue; }
    if (NOISE_LINE.test(text) || !text.trim()) continue;
    // Put a cut before every inline label, then split at sentence punctuation.
    const cuts = new Set<number>();
    for (const match of text.matchAll(LABEL_INLINE)) cuts.add(match.index!);
    for (const match of text.matchAll(/(?<!\d)\.(?!\d)|[!?।…]+/gu)) cuts.add(match.index! + match[0].length);
    const points = [...cuts].filter((point) => point > 0 && point < text.length).sort((a, b) => a - b);
    let from = 0;
    for (const point of [...points, text.length]) {
      if (point > from) pieces.push({ ns: line.s + from, ne: line.s + point, block });
      from = point;
    }
  }
  return pieces;
}

/** Splits a long unpunctuated piece into chunks of roughly 10-26 words, preferably before words like "और", "लेकिन", "but". */
function softSplit(norm: string, piece: RawPiece): RawPiece[] {
  const words = Array.from(norm.slice(piece.ns, piece.ne).matchAll(/\S+/gu), (match) => ({ s: piece.ns + match.index!, e: piece.ns + match.index! + match[0].length, w: match[0] }));
  if (words.length <= MAX_WORDS) return [piece];
  const out: RawPiece[] = [];
  let start = 0;
  while (words.length - start > MAX_WORDS) {
    let cut = -1;
    for (let k = start + MIN_CHUNK; k <= Math.min(start + MAX_WORDS, words.length - 4); k += 1) {
      if (SOFT_BREAK.has(words[k].w.replace(/[,;:]+$/u, ""))) cut = k; // the last soft break inside the window
    }
    if (cut < 0) cut = start + 22;
    out.push({ ns: words[start].s, ne: words[cut - 1].e, block: piece.block });
    start = cut;
  }
  out.push({ ns: words[start].s, ne: words[words.length - 1].e, block: piece.block });
  return out;
}

export function segment(raw: string, mapped: Mapped = normalizeMapped(raw)): Unit[] {
  const { norm, map } = mapped;
  const units: Unit[] = [];
  for (const piece of sentencePieces(norm).flatMap((item) => softSplit(norm, item))) {
    let ns = piece.ns;
    let label: string | undefined;
    const head = norm.slice(ns, piece.ne);
    const found = LABEL_AT_START.exec(head);
    if (found) { label = found[0].replace(/\s*[:：]\s*$/u, "").trim(); ns += found[0].length; }
    // Trim spaces and punctuation at the edges, but keep a closing "?" for the question test.
    let ne = piece.ne;
    while (ns < ne && /[\s,;:\-–—"'“”]/u.test(norm[ns])) ns += 1;
    while (ne > ns && /[\s,;:\-–—"'“”]/u.test(norm[ne - 1])) ne -= 1;
    if (ne <= ns) continue;
    const n = norm.slice(ns, ne);
    const words = n.split(/\s+/u).filter((w) => /[\p{L}\p{N}]/u.test(w)).length;
    if (words === 0) continue;
    const s = map[ns];
    const e = map[ne];
    units.push({ s, e, ns, ne, text: raw.slice(s, e).trim(), n, words, label, block: piece.block, asked: /\?$/u.test(n) });
  }
  return units;
}

/** Index of the unit that contains a position of the normalised text (units are sorted; positions between units go to the previous one). */
export function unitAt(units: Unit[], position: number) {
  let low = 0;
  let high = units.length - 1;
  let found = -1;
  while (low <= high) {
    const mid = (low + high) >> 1;
    if (units[mid].ns <= position) { found = mid; low = mid + 1; } else high = mid - 1;
  }
  return found;
}

export const clip = (value: string, max: number) => {
  const text = value.replace(/\s+/gu, " ").trim();
  if (text.length <= max) return text;
  const cut = text.slice(0, max - 1);
  const space = cut.lastIndexOf(" ");
  return `${(space > max * 0.6 ? cut.slice(0, space) : cut).trimEnd()}…`;
};
